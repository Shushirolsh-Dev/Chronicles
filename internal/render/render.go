package render

import (
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/charmbracelet/lipgloss"
	"github.com/Shushirolsh-Dev/Chronicles/internal/journal"
)

var (
	titleStyle = lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color("255"))
	mutedStyle = lipgloss.NewStyle().Foreground(lipgloss.Color("245"))
	dateStyle = lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color("110"))
	hashStyle = lipgloss.NewStyle().Foreground(lipgloss.Color("108"))
	authorStyle = lipgloss.NewStyle().Foreground(lipgloss.Color("245"))
	ruleStyle = lipgloss.NewStyle().Foreground(lipgloss.Color("238"))
)

func sortedDates(groups map[string][]journal.Entry) []string {
	dates := make([]string, 0, len(groups))
	for date := range groups { dates = append(dates, date) }
	sort.Sort(sort.Reverse(sort.StringSlice(dates)))
	return dates
}

func Journal(repoName string, entries []journal.Entry, days int) string {
	var b strings.Builder
	b.WriteString(titleStyle.Render("CHRONICLES") + "\n")
	b.WriteString(mutedStyle.Render(fmt.Sprintf("%s  ·  last %d days", repoName, days)) + "\n\n")
	if len(entries) == 0 {
		b.WriteString(mutedStyle.Render("No commits found in this period.") + "\n")
		return b.String()
	}
	groups := journal.GroupByDate(entries, time.Local)
	today := time.Now().In(time.Local).Format("2006-01-02")
	yesterday := time.Now().In(time.Local).AddDate(0, 0, -1).Format("2006-01-02")
	for _, date := range sortedDates(groups) {
		parsed, _ := time.ParseInLocation("2006-01-02", date, time.Local)
		label := strings.ToUpper(parsed.Format("02 Jan 2006"))
		if date == today { label = "TODAY · " + label } else if date == yesterday { label = "YESTERDAY · " + label }
		b.WriteString(dateStyle.Render(label) + "\n")
		b.WriteString(ruleStyle.Render("──────────────────────────────────────────────") + "\n")
		for _, entry := range groups[date] {
			hash := entry.Hash
			if len(hash) > 7 { hash = hash[:7] }
			b.WriteString("  " + hashStyle.Render(hash) + "  " + entry.Subject + "\n")
			if entry.Author != "" { b.WriteString("           " + authorStyle.Render(entry.Author) + "\n") }
			b.WriteString("\n")
		}
	}
	b.WriteString(mutedStyle.Render(fmt.Sprintf("%d commits across %d days", len(entries), len(groups))) + "\n")
	return b.String()
}

func Markdown(repoName string, entries []journal.Entry, days int) string {
	var b strings.Builder
	b.WriteString("# Changelog\n\n")
	b.WriteString(fmt.Sprintf("> Generated by Chronicles from **%s** · last %d days\n\n", repoName, days))
	if len(entries) == 0 { b.WriteString("No commits found in this period.\n"); return b.String() }
	groups := journal.GroupByDate(entries, time.Local)
	for _, date := range sortedDates(groups) {
		b.WriteString("## " + date + "\n\n")
		for _, entry := range groups[date] {
			hash := entry.Hash
			if len(hash) > 7 { hash = hash[:7] }
			subject := strings.ReplaceAll(entry.Subject, "\n", " ")
			b.WriteString(fmt.Sprintf("- **%s** — %s", hash, subject))
			if entry.Author != "" { b.WriteString(" _(" + entry.Author + ")_") }
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	return b.String()
}
